def process_file(filepath):
    with open(filepath, 'r', encoding='utf-8') as f:
        content = f.read()

    original = content

    # --- Cancel/page.jsx ---
    content = content.replace('?? ????? ????? ??????', 'Payment Cancelled')
    content = content.replace('?? ????? ????? ????? ????? ??? ??? ??? ?? ????? ?? ??????. ????? ?????? ?????? ?? ?? ???.', 'Your payment has been cancelled successfully. No charges were made. You can return to shopping at any time.')
    content = content.replace('?????? ????????', 'Return to Products')
    content = content.replace('?????? ????????', 'Home Page')

    # --- Success/page.jsx ---
    content = content.replace('??? ?????? ?? ?????!', 'Payment Verification Failed!')
    content = content.replace('?????? ?? ????? ?? ????? ????? ????? ?????? ??. ???? ???????? ??? ???? ?? ??????? ?? ????? ?????.', 'Sorry, we could not confirm your payment. Please try again or contact support.')
    content = content.replace('?????? ????????', 'Return to Home')
    content = content.replace('?? ?????? ?? ????? ?????!', 'Order Verified Successfully!')
    content = content.replace('????? ?????? ????? ???? ??????? ??? ?????? ?????? ?????? ?????.', 'Thank you for shopping with us! We will contact you soon to confirm shipping details.')
    content = content.replace('???? ?????:', 'Order ID:')
    content = content.replace('?????? ???????', 'Go to Orders')
    content = content.replace('????? ??????', 'Sign In')
    content = content.replace('????????', 'Products')
    content = content.replace('>????????<', '>Home<') # to avoid partial matches
    content = content.replace('???? ?????? ?? ???? ????? ??????...', 'Verifying payment and order status...')

    if original != content:
        with open(filepath, 'w', encoding='utf-8') as f:
            f.write(content)
        print(f"Updated UI text in: {filepath}")

